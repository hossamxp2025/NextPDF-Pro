"""Generate source/release identity from src.version, without building binaries."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.version import APP_VERSION, BUILD_ID, RELEASE_STATUS


def outputs():
    numbers = tuple(int(part) for part in APP_VERSION.split("."))
    if len(numbers) != 3:
        raise ValueError("Windows metadata requires major.minor.patch")
    quad = numbers + (0,)
    windows_version = ".".join(str(n) for n in quad)
    resource = f'''# Generated by build/generate_metadata.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={quad!r}, prodvers={quad!r}, mask=0x3f,
                   flags=0, OS=0x40004, fileType=1, subtype=0, date=(0,0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('CompanyName', 'NextPDF'),
    StringStruct('FileDescription', 'NextPDF Pro - Professional PDF Editor'),
    StringStruct('FileVersion', '{windows_version}'),
    StringStruct('InternalName', 'NextPDF-Pro'),
    StringStruct('OriginalFilename', 'NextPDF-Pro.exe'),
    StringStruct('ProductName', 'NextPDF Pro'),
    StringStruct('ProductVersion', '{APP_VERSION}'),
    StringStruct('Comments', 'Build {BUILD_ID}; {RELEASE_STATUS}')
  ])]), VarFileInfo([VarStruct('Translation', [1033,1200])])])
'''
    return {
        ROOT / "VERSION.txt": f"NextPDF Pro\nVersion: {APP_VERSION}\nBuild: {BUILD_ID}\nStatus: {RELEASE_STATUS}\nPlatform: Windows x64\n",
        ROOT / "build/version_info.txt": resource,
        ROOT / "build/version.iss": f'; Generated from src.version\n#define MyAppVersion "{APP_VERSION}"\n',
    }


def generate(check=False):
    for path, text in outputs().items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                raise ValueError(f"Stale generated metadata: {path}")
        else:
            path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    generate(check="--check" in sys.argv)
